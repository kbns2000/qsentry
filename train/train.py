#!/usr/bin/env python3
"""Train the qsentry tiny MLP and export it as a C header.

usage: train.py train.csv val.csv out_header.h
Pure numpy (no ML framework) so the whole pipeline is auditable.
SPDX-License-Identifier: Apache-2.0
"""
import sys
import numpy as np

NFEAT, NCH, NHID, NCLASS = 8, 4, 16, 5
CLASSES = ["ok", "stuck", "drift", "spike", "noise"]


def load(path):
    d = np.loadtxt(path, delimiter=",", skiprows=1, dtype=np.float32)
    ch = d[:, 0].astype(int)
    y = d[:, 1].astype(int)
    f = d[:, 2:2 + NFEAT]
    return ch, y, f


def make_x(ch, f, mu, sd):
    oh = np.eye(NCH, dtype=np.float32)[ch]
    return np.hstack([(f - mu) / sd, oh]).astype(np.float32)


def forward(p, x):
    h = np.maximum(0, x @ p["W1"].T + p["b1"])
    o = h @ p["W2"].T + p["b2"]
    o -= o.max(1, keepdims=True)
    e = np.exp(o)
    return h, e / e.sum(1, keepdims=True)


def train(x, y, epochs=60, lr=3e-3, seed=0, batch=256):
    rng = np.random.default_rng(seed)
    nin = x.shape[1]
    p = {
        "W1": (rng.standard_normal((NHID, nin)) * np.sqrt(2 / nin)).astype(np.float32),
        "b1": np.zeros(NHID, np.float32),
        "W2": (rng.standard_normal((NCLASS, NHID)) * np.sqrt(2 / NHID)).astype(np.float32),
        "b2": np.zeros(NCLASS, np.float32),
    }
    # class weights: balance the OK-heavy dataset
    cnt = np.bincount(y, minlength=NCLASS).astype(np.float32)
    cw = np.sqrt(cnt.sum() / (NCLASS * np.maximum(cnt, 1))).astype(np.float32)
    m = {k: np.zeros_like(v) for k, v in p.items()}
    v = {k: np.zeros_like(v) for k, v in p.items()}
    t = 0
    for ep in range(epochs):
        idx = rng.permutation(len(x))
        for s in range(0, len(x), batch):
            b = idx[s:s + batch]
            xb, yb = x[b], y[b]
            h, pr = forward(p, xb)
            w = cw[yb][:, None]
            g = pr.copy()
            g[np.arange(len(yb)), yb] -= 1
            g *= w / len(yb)
            grads = {
                "W2": g.T @ h, "b2": g.sum(0),
            }
            gh = (g @ p["W2"]) * (h > 0)
            grads["W1"] = gh.T @ xb
            grads["b1"] = gh.sum(0)
            t += 1
            for k in p:
                grads[k] += 1e-4 * p[k] if k.startswith("W") else 0
                m[k] = 0.9 * m[k] + 0.1 * grads[k]
                v[k] = 0.999 * v[k] + 0.001 * grads[k] ** 2
                mh = m[k] / (1 - 0.9 ** t)
                vh = v[k] / (1 - 0.999 ** t)
                p[k] -= (lr * mh / (np.sqrt(vh) + 1e-8)).astype(np.float32)
    return p


def confusion(p, x, y):
    _, pr = forward(p, x)
    yh = pr.argmax(1)
    cm = np.zeros((NCLASS, NCLASS), int)
    for a, b in zip(y, yh):
        cm[a, b] += 1
    return cm, (yh == y).mean()


def c_arr(a):
    if a.ndim == 1:
        return "{" + ", ".join(f"{v:.7g}f" for v in a) + "}"
    return "{\n    " + ",\n    ".join(c_arr(r) for r in a) + "\n}"


def main():
    tr, va, out = sys.argv[1:4]
    P = sys.argv[4] if len(sys.argv) > 4 else "QS"
    ch, y, f = load(tr)
    vch, vy, vf = load(va)
    mu = f.mean(0)
    sd = f.std(0) + 1e-6
    x, vx = make_x(ch, f, mu, sd), make_x(vch, vf, mu, sd)
    p = train(x, y)
    cm, acc = confusion(p, vx, vy)
    print(f"train rows {len(y)}  val rows {len(vy)}  val accuracy {acc:.4f}")
    print("confusion (rows = truth, cols = predicted):", CLASSES)
    for i, r in enumerate(cm):
        print(f"  {CLASSES[i]:>6}", r)
    with open(out, "w") as fh:
        fh.write("/* Generated by train/train.py - do not edit.\n")
        fh.write(f" * validation accuracy {acc:.4f} on {len(vy)} held-out windows\n */\n")
        fh.write(f"static const float {P}_MU[QS_NFEAT] = {c_arr(mu)};\n")
        fh.write(f"static const float {P}_SIGMA[QS_NFEAT] = {c_arr(sd)};\n")
        fh.write(f"static const float {P}_W1[QS_NHID][QS_NIN] = {c_arr(p['W1'])};\n")
        fh.write(f"static const float {P}_B1[QS_NHID] = {c_arr(p['b1'])};\n")
        fh.write(f"static const float {P}_W2[QS_NCLASS][QS_NHID] = {c_arr(p['W2'])};\n")
        fh.write(f"static const float {P}_B2[QS_NCLASS] = {c_arr(p['b2'])};\n")


if __name__ == "__main__":
    main()
